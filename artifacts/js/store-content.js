function cloneStoreContent(src) {
  return JSON.parse(JSON.stringify(src || DEFAULT_STORE_CONTENT));
}

function mergeStoreContent(saved) {
  const base = cloneStoreContent(DEFAULT_STORE_CONTENT);
  if (!saved || typeof saved !== 'object') return base;

  const mergeObj = (target, patch) => {
    if (!patch || typeof patch !== 'object' || Array.isArray(patch)) return;
    Object.keys(patch).forEach((key) => {
      const val = patch[key];
      if (Array.isArray(val)) {
        target[key] = val.map((item) => (item && typeof item === 'object' ? { ...item } : item));
      } else if (val && typeof val === 'object') {
        if (!target[key] || typeof target[key] !== 'object' || Array.isArray(target[key])) {
          target[key] = {};
        }
        mergeObj(target[key], val);
      } else if (val !== undefined) {
        target[key] = val;
      }
    });
  };

  mergeObj(base, saved);
  return base;
}
