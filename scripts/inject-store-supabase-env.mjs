#!/usr/bin/env node
/**
 * Write artifacts/js/supabase-env.js from public env vars.
 * Uses VITE_SUPABASE_URL + VITE_SUPABASE_ANON_KEY only (never service_role).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outFile = path.join(root, 'artifacts/js/supabase-env.js');

function readEnvFile(filePath) {
  try {
    const text = fs.readFileSync(filePath, 'utf8');
    const map = {};
    for (const line of text.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq < 1) continue;
      const key = trimmed.slice(0, eq).trim();
      let val = trimmed.slice(eq + 1).trim();
      if (
        (val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))
      ) {
        val = val.slice(1, -1);
      }
      map[key] = val;
    }
    return map;
  } catch {
    return {};
  }
}

const fileEnv = {
  ...readEnvFile(path.join(root, '.env')),
  ...readEnvFile(path.join(root, '.env.local')),
};

const url = String(
  process.env.VITE_SUPABASE_URL || fileEnv.VITE_SUPABASE_URL || '',
).trim();
const anonKey = String(
  process.env.VITE_SUPABASE_ANON_KEY || fileEnv.VITE_SUPABASE_ANON_KEY || '',
).trim();

if (/service_role/i.test(anonKey)) {
  console.error('inject-store-supabase-env: refusing service_role key in anon slot');
  process.exit(1);
}

const body = `/**
 * AUTO-GENERATED by scripts/inject-store-supabase-env.mjs — do not edit by hand.
 * Public anon config only. Rebuild with npm run build:store after changing env.
 */
window.__RACHAWEI_SUPABASE__ = {
  url: ${JSON.stringify(url)},
  anonKey: ${JSON.stringify(anonKey)},
};
`;

fs.writeFileSync(outFile, body, 'utf8');
if (url && anonKey) {
  console.log('inject-store-supabase-env: wrote supabase-env.js (url + anon key present)');
} else {
  console.log(
    'inject-store-supabase-env: wrote supabase-env.js (env empty — Store will use catalog/IndexedDB fallback)',
  );
}
