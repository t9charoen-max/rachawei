#!/usr/bin/env node
/**
 * Inject VITE_SUPABASE_URL + VITE_SUPABASE_ANON_KEY into store static JS.
 * Runs at build time (Vercel / local). Never embeds service_role.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, 'artifacts/js/supabase-env.js');
const umdSrc = path.join(root, 'node_modules/@supabase/supabase-js/dist/umd/supabase.js');
const umdDest = path.join(root, 'artifacts/js/supabase.umd.js');

let url = String(process.env.VITE_SUPABASE_URL || '').trim();
let anonKey = String(process.env.VITE_SUPABASE_ANON_KEY || '').trim();
const isVercel = process.env.VERCEL === '1' || process.env.VERCEL === 'true';
const fallbackPath = path.join(root, 'artifacts/js/supabase-public-fallback.json');

function loadPublicFallback() {
  try {
    const raw = JSON.parse(fs.readFileSync(fallbackPath, 'utf8'));
    return {
      url: String(raw.url || '').trim(),
      anonKey: String(raw.anonKey || '').trim(),
    };
  } catch {
    return { url: '', anonKey: '' };
  }
}

function isValidSupabaseUrl(value) {
  try {
    const parsed = new URL(value);
    if (parsed.protocol !== 'https:') return false;
    if (process.env.ALLOW_CUSTOM_SUPABASE_HOST === '1') return true;
    return (
      parsed.hostname.endsWith('.supabase.co') ||
      parsed.hostname.endsWith('.supabase.in')
    );
  } catch {
    return false;
  }
}

function isValidAnonKey(value, supabaseUrl) {
  if (!value || value === supabaseUrl) return false;
  if (/service_role/i.test(value)) return false;
  return (
    value.startsWith('eyJ') ||
    value.startsWith('sb_publishable_') ||
    value.startsWith('sb_')
  );
}

if (url && /service_role/i.test(anonKey)) {
  console.error('inject-supabase-env: refusing to embed a service_role key in the frontend');
  process.exit(1);
}

if (url && /localhost|127\.0\.0\.1/i.test(url) && process.env.ALLOW_LOCAL_SUPABASE !== '1') {
  console.warn('inject-supabase-env: warning — VITE_SUPABASE_URL looks like localhost');
}

let urlOk = Boolean(url) && isValidSupabaseUrl(url);
let keyOk = Boolean(anonKey) && isValidAnonKey(anonKey, url);
let configured = urlOk && keyOk;
let source = configured ? 'env' : '';

if ((url || anonKey) && !configured) {
  const reasons = [];
  if (!urlOk) {
    reasons.push(
      'VITE_SUPABASE_URL must be https://YOUR_PROJECT.supabase.co (not the publishable/anon key)',
    );
  }
  if (!keyOk) {
    reasons.push(
      'VITE_SUPABASE_ANON_KEY must be the anon/publishable key (eyJ… or sb_publishable_…), and must differ from the URL',
    );
  }
  console.error('inject-supabase-env: invalid Supabase env:\n- ' + reasons.join('\n- '));
  if (process.env.FAIL_ON_BAD_SUPABASE_ENV === '1') {
    process.exit(1);
  }
}

if (!configured) {
  const fb = loadPublicFallback();
  if (
    fb.url &&
    fb.anonKey &&
    isValidSupabaseUrl(fb.url) &&
    isValidAnonKey(fb.anonKey, fb.url) &&
    !/service_role/i.test(fb.anonKey)
  ) {
    url = fb.url;
    anonKey = fb.anonKey;
    urlOk = true;
    keyOk = true;
    configured = true;
    source = 'public_fallback';
    console.warn(
      'inject-supabase-env: using artifacts/js/supabase-public-fallback.json (set Vercel env on project rachawei for Production preferred)',
    );
  } else if (isVercel) {
    console.error(
      'inject-supabase-env: Vercel build will continue with configured=false (catalog fallback). Fix Project Settings → Environment Variables on rachawei, then Redeploy.',
    );
  }
}

const body = `/**
 * AUTO-GENERATED by scripts/inject-supabase-env.mjs — อย่าแก้มือ
 * Source: ${source || 'none'} (VITE_SUPABASE_* or public fallback)
 */
window.__RACHAWEI_SUPABASE__ = {
  url: ${JSON.stringify(configured ? url : '')},
  anonKey: ${JSON.stringify(configured ? anonKey : '')},
  configured: ${configured ? 'true' : 'false'}
};
`;

fs.writeFileSync(outPath, body, 'utf8');

if (fs.existsSync(umdSrc)) {
  fs.copyFileSync(umdSrc, umdDest);
  console.log('inject-supabase-env: copied supabase UMD → artifacts/js/supabase.umd.js');
} else {
  console.error('inject-supabase-env: UMD bundle not found — run npm install first');
  if (configured) process.exit(1);
}

console.log(
  configured
    ? `inject-supabase-env: Supabase configured for store build (${source})`
    : 'inject-supabase-env: Supabase env missing/invalid — store will use catalog fallback until env is set',
);
